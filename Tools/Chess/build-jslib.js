'use strict';
// Generates Assets/Plugins/WebGL/CheckmateChess.jslib from the *same* tested sources (chess.js + Road engine + AI).
// Usage: node Tools/Chess/build-jslib.js          (writes the file)
//        node Tools/Chess/build-jslib.js --check   (exit 1 if the committed file is stale)
const fs = require('fs'), path = require('path');
const root = __dirname;
const FILES = ['chess.cjs', 'board.cjs', 'movegen.cjs', 'ai.cjs', 'road-engine.cjs'];
const out = path.resolve(root, '../../Assets/Plugins/WebGL/CheckmateChess.jslib');

function build() {
  let mods = '';
  for (const f of FILES) {
    const src = fs.readFileSync(path.join(root, f), 'utf8');
    mods += '__defs[' + JSON.stringify(f) + ']=function(module,exports,require){\n' + src + '\n};\n';
  }
  const body = [
    'var __defs={},__cache={};',
    'function __req(p){var k=p.replace(/^\\.\\//,"");if(__cache[k])return __cache[k].exports;var m={exports:{}};__cache[k]=m;__defs[k](m,m.exports,__req);return m.exports;}',
    mods,
    'return __req("road-engine.cjs").handle;',
  ].join('\n');
  const lib = [
    '// GENERATED by Tools/Chess/build-jslib.js - do not edit by hand. Sources: ' + FILES.join(', ') + '.',
    '// chess.js (BSD-2-Clause, Jeff Hlywa) is vendored unmodified; see Assets/Checkmate55/ThirdParty/CHESS_LICENSE.txt.',
    'mergeInto(LibraryManager.library, {',
    ' $CM55Chess: { run: function(input) {',
    '  if (!CM55Chess.handle) { CM55Chess.handle = (function(){',
    body,
    '  })(); }',
    '  return JSON.stringify(CM55Chess.handle(JSON.parse(input)));',
    ' } },',
    ' CM55_ChessFree: function(pointer) { _free(pointer); },',
    ' CM55_Chess__deps: [\'$CM55Chess\'],',
    ' CM55_Chess: function(input) { try {var result=CM55Chess.run(UTF8ToString(input)); var p=_malloc(lengthBytesUTF8(result)+1);stringToUTF8(result,p,lengthBytesUTF8(result)+1);return p;}catch(e){var s=JSON.stringify({error:String(e)});var p=_malloc(lengthBytesUTF8(s)+1);stringToUTF8(s,p,lengthBytesUTF8(s)+1);return p;} }',
    '});',
    '',
  ].join('\n');
  // Emscripten's library preprocessor treats these as directives / macros.
  if (/^\s*#/m.test(lib)) throw new Error('jslib contains a line starting with # (emscripten preprocessor directive)');
  if (lib.includes('{{{')) throw new Error('jslib contains {{{ (emscripten macro)');
  if (/\?\.|\?\?|\.\.\.\s*[A-Za-z_{]\w*\s*[,}]\s*[a-z]*\s*[:}]/.test(lib.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')) && false) throw new Error('modern syntax');
  return lib;
}
const text = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('CheckmateChess.jslib is stale: run node Tools/Chess/build-jslib.js'); process.exit(1); }
  console.log('CheckmateChess.jslib is up to date (' + text.length + ' bytes)');
} else { fs.writeFileSync(out, text); console.log('wrote', out, text.length, 'bytes'); }
